const dictionaries = { de, en };
export type Locale = keyof typeof dictionaries;

let current: Locale = getLocales()[0]?.languageCode === 'de' ? 'de' : 'en';

export function setLocale(l: Locale) {
  current = l;
}
export function getLocale(): Locale {
  return current;
}

type Path<T, P extends string = ''> = {
  [K in keyof T & string]: T[K] extends string ? `${P}${K}` : Path<T[K], `${P}${K}.`>;
}[keyof T & string];
export type TKey = Path<Dict>;

/** Übersetzt einen Schlüssel wie "charge.checkIn" und ersetzt {{platzhalter}}. */
export function t(key: TKey | string, vars?: Record<string, string | number>): string {
  const lookup = (d: unknown) =>
    key.split('.').reduce<unknown>((o, k) => (o && typeof o === 'object' ? (o as Record<string, unknown>)[k] : undefined), d);
  let s = lookup(dictionaries[current]) ?? lookup(de);
  if (typeof s !== 'string') return key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = (s as string).replaceAll(`{{${k}}}`, String(v));
  return s as string;
}
